// ══ NOTES GENERATOR ══
// Tries the AI providers configured in "AI Provider Keys" (see
// tools-common.js) in order; if none are configured, or every configured one
// fails, it falls back to a fully offline outline template that always
// works. Either way, the result is labelled honestly so it's never
// mistaken for the other.

function buildOfflineOutline(topic, subject, boardLabel) {
  return `
    <h3><i class="ti ti-notes"></i> ${topic} — ${subject}</h3>
    <p style="margin:6px 0 12px;color:var(--muted);font-size:0.85rem">A fill-in outline for ${boardLabel} (generated offline — no AI provider configured or available right now). Fill in each section from your textbook and class notes.</p>
    <h4>Overview</h4>
    <p>Write 2–3 sentences summarising what "${topic}" covers and why it matters for the ${subject} syllabus.</p>
    <h4>Key Concepts</h4>
    <ul>
      <li>List the core ideas or processes involved in ${topic}</li>
      <li>Note how each concept connects to the wider ${subject} topic list</li>
      <li>Add any formulae, equations or laws that apply here</li>
    </ul>
    <h4>Important Definitions</h4>
    <ul>
      <li>Term 1 — definition</li>
      <li>Term 2 — definition</li>
    </ul>
    <h4>Common Exam Mistakes</h4>
    <ul>
      <li>Mistakes examiners frequently flag on this topic</li>
      <li>Command words to watch out for (e.g. "explain" vs "describe")</li>
    </ul>
    <h4>Quick Recall Summary</h4>
    <ul>
      <li>5 bullet points you could read in the last 5 minutes before the exam</li>
    </ul>
    <div style="margin-top:14px;padding-top:10px;border-top:1px solid var(--border);font-size:0.78rem;color:var(--muted)">Offline outline for ${boardLabel} · Fill it in, then cross-check with SaveMyExams or ZNotes and your textbook.</div>
  `;
}

// Shell for an AI answer. The body is filled in by ssRenderRich (rich-output.js):
// real Markdown with tables, bold, bullets and diagrams. Real diagrams from
// Wikimedia Commons are added underneath once they've been found.
function renderAINotesShell(topic, subject, boardLabel, providerLabel) {
  return `
    <h3><i class="ti ti-sparkles"></i> ${ssEscapeHTML(topic)} — ${ssEscapeHTML(subject)}</h3>
    <p style="margin:6px 0 12px;color:var(--muted);font-size:0.85rem">AI-generated for ${ssEscapeHTML(boardLabel)} via ${ssEscapeHTML(providerLabel)}. Always double-check against your textbook and syllabus.</p>
    <div class="ss-rich" id="nhAiBody"></div>
    <div class="ss-rich" id="nhAiFigures"></div>
    <div style="margin-top:14px;padding-top:10px;border-top:1px solid var(--border);font-size:0.78rem;color:var(--muted)">Generated by ${ssEscapeHTML(providerLabel)} · Not a substitute for your class notes.</div>
  `;
}

async function showAINotes(resultEl, topic, subject, boardLabel, providerLabel, rawText) {
  const { body, query } = ssSplitDiagramQuery(rawText);
  resultEl.innerHTML = renderAINotesShell(topic, subject, boardLabel, providerLabel);
  const bodyEl = resultEl.querySelector('#nhAiBody');
  bodyEl.innerHTML = ssSimpleMarkdown(body); // readable straight away, even if the renderer can't load
  await ssRenderRich(bodyEl, body);
  ssShowDiagrams(resultEl.querySelector('#nhAiFigures'), query || `${topic} ${subject}`);
}

async function generateAINotes() {
  const curriculum = document.getElementById('nhGenCurriculum').value;
  const level = document.getElementById('nhGenLevel').value;
  const subject = document.getElementById('nhGenSubject').value;
  const topic = document.getElementById('nhGenTopic').value.trim();
  if (!subject || !topic) { alert('Please select a subject and enter a topic!'); return; }

  const resultEl = document.getElementById('nhAiResult');
  const boardLabel = curriculum ? `${curriculum} ${level}` : `${level}`;
  const btn = document.getElementById('nhGenBtn');

  resultEl.style.display = 'block';

  if (!ssHasAnyAIPath()) {
    resultEl.innerHTML = buildOfflineOutline(topic, subject, boardLabel);
    addPoints(8, `Notes outline: ${subject} — ${topic}`);
    return;
  }

  if (btn) { btn.disabled = true; btn.innerHTML = `<i class="ti ti-loader-2" style="animation:spin 1s linear infinite"></i> Asking AI…`; }
  resultEl.innerHTML = `<p style="color:var(--muted);font-size:0.85rem"><i class="ti ti-loader-2" style="animation:spin 1s linear infinite"></i> Generating…</p>`;

  const depthRule = level.startsWith('O Level')
    ? `Write at O Level / IGCSE depth: the key ideas, processes and terms a 15-16 year old needs for the exam, in simple clear language. Leave out university-level and A Level detail (for example detailed sub-stages, advanced mechanisms, checkpoints and specialist terminology) unless it is clearly part of the O Level / IGCSE syllabus. When unsure, leave it out.`
    : `Write at A Level / IAL depth: include the extra detail, mechanisms and precise terminology that level requires, explained clearly.`;
  const system = `You are a revision-notes writer for a ${boardLabel} student. Write clean GitHub-flavoured Markdown, exam-focused, about 400-500 words.

Use exactly these sections, each starting with a "## " heading: Overview (2-3 sentences), Key Concepts (short bullet points with the key terms in **bold**), Important Definitions (bullets), Common Exam Mistakes (bullets), Quick Recall Summary (5 bullets).

Add a Markdown table (with a header row) under Key Concepts only when the topic compares things, such as two processes or types.

If the topic is a process, cycle or sequence, add one Mermaid diagram in a fenced code block labelled mermaid. Use "flowchart TD", short node labels written like A[Label] using only plain words (no brackets, quotes, colons or slashes inside labels), and arrows written -->. Example:
\`\`\`mermaid
flowchart TD
  A[Interphase] --> B[Prophase]
  B --> C[Metaphase]
\`\`\`

${depthRule} Spell the exam board and level exactly as given: ${boardLabel}. Do not use horizontal rules or emojis.

Your very last line must be exactly: DIAGRAM_SEARCH: followed by 2-4 keywords for a labelled textbook diagram of this topic (for example: DIAGRAM_SEARCH: mitosis stages).`;
  const prompt = `Subject: ${subject}\nBoard/Level: ${boardLabel}\nTopic: ${topic}\n\nWrite the revision notes outline described in the system prompt.`;

  const result = await ssAIComplete(system, prompt, (providerName) => {
    if (btn) btn.innerHTML = `<i class="ti ti-loader-2" style="animation:spin 1s linear infinite"></i> Asking ${providerName}…`;
  });

  if (btn) { btn.disabled = false; btn.innerHTML = `<i class="ti ti-notes"></i> Generate Notes`; }

  if (result) {
    showAINotes(resultEl, topic, subject, boardLabel, result.provider, result.text);
    addPoints(10, `AI notes: ${subject} — ${topic}`);
  } else {
    resultEl.innerHTML = buildOfflineOutline(topic, subject, boardLabel);
    addPoints(8, `Notes outline: ${subject} — ${topic}`);
  }
}
